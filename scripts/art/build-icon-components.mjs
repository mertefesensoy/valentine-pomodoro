#!/usr/bin/env node
/**
 * build-icon-components.mjs — the app's icons, stickers and mark as react-native-svg data
 * (Phase 1 D1/D2; NFR-UX-002, ADR-0047).
 *
 *   node scripts/art/build-icon-components.mjs           write src/components/{icons,stickers}/art/*.ts
 *   node scripts/art/build-icon-components.mjs --check   regenerate in memory and compare; exit 1 on any difference
 *
 * Contract
 *   in : the VectorCraft exports in art/out/ (built by scripts/art/build.mjs):
 *        - icon/icon-<name>.svg                → icons, drawn in currentColor (one ink, any theme)
 *        - illustration/{pomo,doro}-<pose>.svg → stickers, keeping their own fills
 *        - illustration/welcome-*.svg          → the welcome morph's layers (D1), keeping their fills
 *        - logo/mark-{colour,reversed,single-cocoa,single-white}.svg → the mark's versions (C5)
 *   out: one data module per drawing, `export const <camelName>: Glyph | StickerArt`, under
 *        src/components/icons/art/ and src/components/stickers/art/. One module each, because
 *        Metro doesn't tree-shake: only the drawings a screen imports reach the bytecode.
 *   how: reads each SVG's viewBox and its <path> elements (d, fill, fill-rule, opacity). Any
 *        other element or attribute stops the script, so nothing the exporter adds later can be
 *        dropped silently. Output is a pure function of the inputs, so --check is byte-exact.
 * Read-only on art/out/; run from the repo root.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CHECK = process.argv.includes('--check');
const HEADER = (src) => `// Generated by scripts/art/build-icon-components.mjs from ${src}. Do not edit.\n`;

const SOURCES = [
    { dir: 'art/out/icon', match: /^icon-(.+)\.svg$/, out: 'src/components/icons/art', kind: 'glyph' },
    { dir: 'art/out/illustration', match: /^((?:pomo|doro)-(?!.*outlined).+|welcome-.+)\.svg$/, out: 'src/components/stickers/art', kind: 'sticker' },
    { dir: 'art/out/logo', match: /^(mark-(?:colour|reversed|single-cocoa|single-white))\.svg$/, out: 'src/components/stickers/art', kind: 'sticker' },
];

const camel = (name) => name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

function attrs(tag) {
    const out = {};
    for (const m of tag.matchAll(/([a-zA-Z:-]+)="([^"]*)"/g)) out[m[1]] = m[2];
    return out;
}

function parse(file) {
    const svg = fs.readFileSync(file, 'utf8');
    const root = svg.match(/<svg\b[^>]*>/);
    if (!root) throw new Error(`${file}: no <svg> element`);
    const viewBox = attrs(root[0]).viewBox;
    if (!viewBox) throw new Error(`${file}: no viewBox`);
    const body = svg.slice(root.index + root[0].length).replace(/<\/svg>\s*$/, '').replace(/<title>[^<]*<\/title>/g, '');
    const paths = [];
    for (const m of body.matchAll(/<(\/?)([a-zA-Z]+)\b([^>]*?)(\/?)>/g)) {
        const [, closing, name, rest] = m;
        if (name === 'g') {
            if (!closing && Object.keys(attrs(rest)).length) throw new Error(`${file}: a <g> with attributes is not supported`);
            continue;
        }
        if (name !== 'path') throw new Error(`${file}: unsupported element <${name}>`);
        const a = attrs(rest);
        for (const k of Object.keys(a)) {
            if (!['d', 'fill', 'fill-rule', 'opacity'].includes(k)) throw new Error(`${file}: unsupported attribute ${k} on <path>`);
        }
        if (a['fill-rule'] && a['fill-rule'] !== 'evenodd' && a['fill-rule'] !== 'nonzero') {
            throw new Error(`${file}: fill-rule ${a['fill-rule']}`);
        }
        paths.push({ d: a.d, fill: a.fill, evenOdd: a['fill-rule'] === 'evenodd', opacity: a.opacity ? Number(a.opacity) : undefined });
    }
    if (!paths.length) throw new Error(`${file}: no paths`);
    return { viewBox, paths };
}

function moduleFor(kind, name, src, { viewBox, paths }) {
    const id = camel(name);
    const lines = paths.map((p) => {
        const parts = [`d: ${JSON.stringify(p.d)}`];
        if (kind === 'sticker') parts.push(`fill: ${JSON.stringify(p.fill ?? '#000000')}`);
        if (p.evenOdd) parts.push('evenOdd: true');
        if (kind === 'sticker' && p.opacity !== undefined) parts.push(`opacity: ${p.opacity}`);
        return `        { ${parts.join(', ')} },`;
    });
    const type = kind === 'glyph' ? 'Glyph' : 'StickerArt';
    const from = kind === 'glyph' ? '../Icon' : '../Sticker';
    return (
        HEADER(src) +
        `import type { ${type} } from '${from}';\n\n` +
        `export const ${id}: ${type} = {\n    viewBox: ${JSON.stringify(viewBox)},\n    paths: [\n${lines.join('\n')}\n    ],\n};\n`
    );
}

const expected = new Map(); // repo path -> content
for (const s of SOURCES) {
    for (const f of fs.readdirSync(path.join(ROOT, s.dir)).sort()) {
        const m = f.match(s.match);
        if (!m) continue;
        const src = `${s.dir}/${f}`;
        expected.set(`${s.out}/${camel(m[1])}.ts`, moduleFor(s.kind, m[1], src, parse(path.join(ROOT, src))));
    }
}

let differences = 0;
for (const out of new Set(SOURCES.map((s) => s.out))) {
    const dir = path.join(ROOT, out);
    const present = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.ts')).map((f) => `${out}/${f}`) : [];
    for (const stale of present.filter((p) => !expected.has(p))) {
        if (CHECK) { differences++; console.log(`✖ ${stale} has no source in art/out/`); }
        else fs.rmSync(path.join(ROOT, stale));
    }
}
for (const [rel, content] of expected) {
    const file = path.join(ROOT, rel);
    if (CHECK) {
        const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') === content;
        if (!same) { differences++; console.log(`✖ ${rel} differs from its source`); }
    } else {
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content);
    }
}
if (CHECK) {
    console.log(differences ? `✖ ${differences} file(s) differ` : `✔ ${expected.size} drawings match their sources`);
    process.exit(differences ? 1 : 0);
}
console.log(`✔ wrote ${expected.size} drawings`);
